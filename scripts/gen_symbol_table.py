#!/usr/bin/env python3
"""Generate switch-mod/src/sym/SymbolTable.inc from switch-mod/syms/mk8dx_symbols.toml.

The .inc is committed so a plain CMake build needs no Python; run this after
editing the TOML. `python scripts/gen_symbol_table.py --check` exits non-zero
when the committed .inc is stale (used by the test suite / CI).

Each generated row is:
    { "<name>", "<mangled>", "<pattern>", <offset>, <address> },
where <address> is the published main-relative address on MK8DX 4.0.1
(0 = none, locate by pattern) and an empty pattern means "address only".
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TOML = REPO / "switch-mod" / "syms" / "mk8dx_symbols.toml"
INC = REPO / "switch-mod" / "src" / "sym" / "SymbolTable.inc"

HEADER = """// AUTO-GENERATED by scripts/gen_symbol_table.py from syms/mk8dx_symbols.toml.
// Do not edit by hand. Rows: name, mangled, pattern, offset, address (4.0.1).
"""


def _validate_pattern(name: str, pat: str) -> None:
    toks = pat.split()
    for tok in toks:
        if tok in ("?", "??"):
            continue
        if len(tok) != 2 or any(c not in "0123456789abcdefABCDEF" for c in tok):
            raise SystemExit(f"{name}: bad pattern token {tok!r}")
    if len(toks) % 4:
        raise SystemExit(f"{name}: pattern must be a whole number of instructions (4 bytes each)")


def _to_int(v) -> int:
    """TOML has no negative hex literals, so offsets may be quoted strings."""
    return int(v, 0) if isinstance(v, str) else int(v)


def render(toml_path: Path = TOML) -> str:
    data = tomllib.loads(toml_path.read_text(encoding="utf-8"))
    rows = []
    seen: set[str] = set()
    for s in data.get("symbols", []):
        name = s["name"]
        if name in seen:
            raise SystemExit(f"duplicate symbol name {name!r}")
        seen.add(name)
        mangled = s.get("mangled", "")
        pat = " ".join(s.get("pattern", "").split())
        _validate_pattern(name, pat)
        off = _to_int(s.get("offset", 0))
        address = _to_int(s.get("address", 0))
        if address % 4 or address < 0:
            raise SystemExit(f"{name}: address must be a non-negative multiple of 4")
        if not pat and not address:
            raise SystemExit(f"{name}: needs a pattern or an address")
        rows.append(f'    {{ "{name}", "{mangled}", "{pat}", {off:#x}, {address:#x} }},')
    return HEADER + "\n".join(rows) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="fail if the .inc is stale")
    args = p.parse_args(argv)
    text = render()
    if args.check:
        current = INC.read_text(encoding="utf-8") if INC.exists() else ""
        if current != text:
            print(f"STALE: {INC} does not match {TOML}; re-run gen_symbol_table.py",
                  file=sys.stderr)
            return 1
        print("OK: SymbolTable.inc is up to date")
        return 0
    INC.parent.mkdir(parents=True, exist_ok=True)
    INC.write_text(text, encoding="utf-8", newline="\n")
    print(f"OK: wrote {INC} ({text.count(chr(10)) - 2} symbols)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
